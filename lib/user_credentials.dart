/// Helper function to validate credentials
/// Supports both:
/// 1. Username = Name, Password = Register Number
/// 2. Handles names with multiple duplicate matches (e.g., duplicate SANJAY S entries)
bool validateVoterCredentials(String username, String password) {
  final cleanUser = username.trim().toUpperCase();
  final cleanPass = password.trim();

  for (final voter in allVotersList) {
    if (voter.name.trim().toUpperCase() == cleanUser && voter.regNo.trim() == cleanPass) {
      return true;
    }
  }
  return false;
}
